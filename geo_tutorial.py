def build_tutorial_report(items=None):
    """构建教程报告。

    items: 最近一次已完成的深度诊断的 diagnosis_items 列表（storage.get_run_items
    的返回值），为 None 或空列表时视为"暂无诊断数据"。

    返回：
    {
        "basics": [...],           # 固定的GEO基础知识，始终返回
        "personalized": [...],     # 按当前诊断结果里Gap出现频次排序的针对性教程，
                                    # 每条附带 count / questions（命中该Gap的问题列表）
        "has_diagnosis_data": bool,
    }
    """
    if not items:
        return {"basics": BASIC_SECTIONS, "personalized": [], "has_diagnosis_data": False}

    gaps_top = aggregate_gaps(items, top_n=len(GAP_TUTORIALS))
    personalized = []
    for g in gaps_top:
        tutorial = GAP_TUTORIALS.get(g["type"])
        if not tutorial:
            continue
        personalized.append({
            **tutorial,
            "gap_type": g["type"],
            "gap_label": g["label"],
            "affected_count": g["count"],
            "affected_questions": g["questions"],
        })

    return {
        "basics": BASIC_SECTIONS,
        "personalized": personalized,
        "has_diagnosis_data": True,
    }
